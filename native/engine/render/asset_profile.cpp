#include "asset_profile.h"

AssetProfile AssetProfile::forModel(ModelKind kind) {
  switch (kind) {
    case ModelKind::Player:
      // 主角盔甲：高光最强最锐利，作为画面焦点。卡通阴影取冷紫调，
      // 受光面保持盔甲固有色；描边最粗一档，主角是画面焦点。
      // 模型为原始 5 倍（0.05f→0.25f，曾放大 20 倍后缩回 1/4）：
      // VFX 经 VfxSizeRatio 自动跟随。
      return {0.25f / 3.0f, 0.0f, {0.16f, 0.24f, 0.27f},
              {0.31f, 0.84f, 0.75f}, 0.75f, 0, 0.42f, 32.0f,
              true, {0.74f, 0.70f, 0.86f}, 0.16f, 0.09f, 0.00038f};
    case ModelKind::Enemy:
      // 敌人：哑光弱高光，退到背景不抢主角。阴影阈值最低，
      // 暗部占比更大；描边最细，与主角拉开层级。
      // 模型放大 3 倍（0.044/3→0.132/3）：描边世界宽度随体量同步
      // 放大 3 倍，保持相对线宽不变；VFX 经 VfxSizeRatio 自动跟随。
      return {0.132f / 3.0f, 0.0f, {0.24f, 0.20f, 0.25f},
              {0.45f, 0.30f, 0.48f}, 0.35f, 1, 0.14f, 12.0f,
              true, {0.60f, 0.62f, 0.74f}, 0.02f, 0.07f, 0.00096f};
    case ModelKind::Boss:
      // Boss：介于两者之间，宽而厚的高光强调体量。
      // yawOffset 必须为 0：boss3d.angle 已按 boss→player 方向计算，
      // 模型局部 +Z 为前方，加 π 会让首领永远背对玩家。
      // 阴影最深最饱和，描边最粗，强调首领体量与压迫感。
      return {0.09f / 3.0f, 0.0f, {0.18f, 0.16f, 0.22f},
              {0.72f, 0.39f, 0.66f}, 0.65f, 3, 0.3f, 20.0f,
              true, {0.55f, 0.50f, 0.66f}, 0.10f, 0.08f, 0.00062f};
    case ModelKind::Npc:
      // NPC（Phase 4）：类人轮廓（体量介于主角与敌人之间），暖金勾边
      // 区分友好单位，高光哑光避免与主角争夺视觉焦点。
      // 模型三轮调整累计放大 4 倍（0.05/3→0.30/3→0.20/3：先 3 倍、
      // 再 2 倍、嫌大缩回 2/3）：描边世界宽度随体量同步变化，保持
      // 相对线宽不变。
      return {0.20f / 3.0f, 0.0f, {0.27f, 0.25f, 0.22f},
              {0.85f, 0.72f, 0.40f}, 0.4f, 0, 0.18f, 16.0f,
              true, {0.72f, 0.70f, 0.74f}, 0.12f, 0.10f, 0.00120f};
  }
  return {};
}
